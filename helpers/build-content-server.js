// Generate deployable server logic from the same model used by the editor.
const fs = require("node:fs");
const path = require("node:path");
const crypto = require("node:crypto");
const root = path.resolve(__dirname, "..");
const site = path.join(root, "src", "pa-knowledge-hub---knoweldgehub");
const seed = JSON.parse(fs.readFileSync(path.join(root, "power-platform", "content-seed.json"), "utf8"));
function id(key) {
  const hex = crypto.createHash("sha256").update("connecthub:" + key).digest("hex");
  return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-5${hex.slice(13, 16)}-a${hex.slice(17, 20)}-${hex.slice(20, 32)}`;
}
for (const row of seed.records) row.itemId = id(row.sourceKey);
seed.homePageId = seed.records.find(row => row.pageUrl === "/")?.sourceKey;
if (!seed.homePageId) throw new Error("Home page metadata is required.");
const pages = new Map();
for (const dir of fs.readdirSync(path.join(site, "web-pages"), { withFileTypes: true }).filter(entry => entry.isDirectory())) {
  const folder = path.join(site, "web-pages", dir.name);
  for (const filename of fs.readdirSync(folder).filter(name => name.endsWith(".webpage.yml"))) {
    const metadata = Object.fromEntries([...fs.readFileSync(path.join(folder, filename), "utf8").matchAll(/^(adx_\w+):\s*([^\r\n]*)/gm)].map(match => [match[1], match[2].trim()]));
    if (metadata.adx_isroot === "true") pages.set(metadata.adx_webpageid, metadata);
  }
}
seed.reservedPaths = [...pages.values()].map(metadata => {
  const parts = [], seen = new Set();
  while (metadata && !seen.has(metadata.adx_webpageid)) {
    seen.add(metadata.adx_webpageid);
    if (metadata.adx_partialurl && metadata.adx_partialurl !== "/") parts.unshift(metadata.adx_partialurl);
    metadata = pages.get(metadata.adx_parentpageid);
  }
  return "/" + parts.join("/").toLowerCase();
}).concat(["/signin", "/signout", "/register", "/account"]);
const model = fs.readFileSync(path.join(site, "web-files", "content.js"), "utf8");
const preamble = "// Generated by helpers/build-content-server.js. Edit power-platform/server sources.\n";
fs.writeFileSync(path.join(site, "server-logic", "AdminHubMaster.js"), preamble + model + "\nconst CONTENT_SEED = " + JSON.stringify(seed) + ";\n" + fs.readFileSync(path.join(root, "power-platform", "server", "AdminHubMaster.source.js"), "utf8"));
const publicSeed = { records: seed.records.filter(row => ["prompt", "agent", "testimony"].includes(row.kind)).map(row => ({ ...row, fields: undefined, editableFields: undefined, templateKey: undefined })) };
fs.writeFileSync(path.join(site, "server-logic", "ContentHub.js"), preamble + "const CONTENT_SEED = " + JSON.stringify(publicSeed) + ";\n" + fs.readFileSync(path.join(root, "power-platform", "server", "ContentHub.source.js"), "utf8"));
console.log(`Built AdminHubMaster and ContentHub with ${seed.records.length} import records.`);
